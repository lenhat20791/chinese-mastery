# Số nét: (số thứ tự bộ cuối cùng, số nét)
_STROKE_ENDS = [
    (6, 1), (29, 2), (60, 3), (94, 4), (117, 5), (146, 6), (166, 7),
    (175, 8), (186, 9), (194, 10), (200, 11), (204, 12), (208, 13),
    (210, 14), (211, 15), (213, 16), (214, 17),
]


def radicals_by_strokes():
    """Trả về [(số nét, [(số thứ tự, chữ, biến thể, tên, nghĩa), ...]), ...]."""
    groups, start = [], 1
    for end, strokes in _STROKE_ENDS:
        items = [(n, *RADICALS[n - 1]) for n in range(start, end + 1)]
        groups.append((strokes, items))
        start = end + 1
    return groups
